import { createHash } from 'node:crypto'
import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises'
import path from 'node:path'
import sharp from 'sharp'

const sourceRoot = 'public/assets/illustrations/figma'
const outputRoot = 'public/assets/illustrations/optimized'
const checkOnly = process.argv.includes('--check')
const manifestPath = 'src/data/optimizedArtwork.ts'
const manifestPrefix = '// Generated by npm run assets:optimize. Do not edit manually.\nexport const optimizedArtwork: Record<string, string> = '
const existingArtwork = checkOnly
  ? JSON.parse((await readFile(manifestPath, 'utf8')).replace(/\r\n/g, '\n').slice(manifestPrefix.length))
  : {}
if (!checkOnly) await mkdir(outputRoot, { recursive: true })
const artwork = {}
const report = []

// Keep the Figma originals; generate browser-ready copies without resizing.
for (const directory of (await readdir(sourceRoot, { withFileTypes: true })).sort((a, b) => a.name.localeCompare(b.name))) {
  if (!directory.isDirectory()) continue
  for (const name of (await readdir(path.join(sourceRoot, directory.name))).sort()) {
    if (!name.endsWith('.png')) continue
    const key = `${directory.name}/${name.slice(0, -4)}`
    const source = await readFile(path.join(sourceRoot, directory.name, name))
    const existingUrl = existingArtwork[key]
    if (checkOnly && (!existingUrl || !/^\/assets\/illustrations\/optimized\/[a-z0-9-]+\.[a-f0-9]{12}\.webp$/.test(existingUrl))) {
      throw new Error(`Missing optimized artwork: ${key}. Run npm run assets:optimize.`)
    }
    const output = checkOnly
      ? await readFile(path.join(outputRoot, path.basename(existingUrl)))
      : await sharp(source).webp({ lossless: true, effort: 6, exact: true }).toBuffer()
    const [before, after] = await Promise.all([
      sharp(source).ensureAlpha().raw().toBuffer({ resolveWithObject: true }),
      sharp(output).ensureAlpha().raw().toBuffer({ resolveWithObject: true }),
    ])
    if (before.info.width !== after.info.width || before.info.height !== after.info.height || !before.data.equals(after.data)) {
      throw new Error(`Pixel verification failed: ${key}. Run npm run assets:optimize.`)
    }
    const hash = createHash('sha256').update(output).digest('hex').slice(0, 12)
    const filename = `${directory.name}--${name.slice(0, -4)}.${hash}.webp`
    artwork[key] = `/assets/illustrations/optimized/${filename}`
    if (checkOnly && existingUrl !== artwork[key]) throw new Error(`Incorrect asset hash: ${key}`)
    if (!checkOnly) await writeFile(path.join(outputRoot, filename), output)
    report.push({ key, originalBytes: source.length, optimizedBytes: output.length })
  }
}

if (checkOnly && Object.keys(existingArtwork).length !== report.length) throw new Error('Stale artwork manifest. Run npm run assets:optimize.')
if (!checkOnly) await writeFile(manifestPath, manifestPrefix + JSON.stringify(artwork, null, 2) + '\n')
const originalBytes = report.reduce((sum, item) => sum + item.originalBytes, 0)
const optimizedBytes = report.reduce((sum, item) => sum + item.optimizedBytes, 0)
const summary = { count: report.length, originalBytes, optimizedBytes, reductionPercent: +(100 * (1 - optimizedBytes / originalBytes)).toFixed(1), pixelIdentical: true }
if (!checkOnly) await writeFile('docs/IMAGE_OPTIMIZATION.json', JSON.stringify({ ...summary, images: report }, null, 2) + '\n')
console.log(JSON.stringify(summary))
